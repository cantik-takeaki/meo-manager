/**
 * 返信の中の「事実を認める表現」「相手の悪口の言い直し」「店の細かい内容」を探す。
 * 古い口コミへの「返信が遅くなり申し訳ありません」は対象外（来店の事実を認める文ではない）。
 */
export function findAffirm(reply, reviewText = '') {
  const r = String(reply || '').replace(/[^。\n]*(返信|ご返信|お返事)が遅くなり[^。\n]*[。\n]?/g, '');
  const low = r.toLowerCase();
  const affirm = [...AFFIRM.filter(w => r.includes(w)), ...AFFIRM_EN.filter(w => low.includes(w))];
  // カタカナだけの短い語は、前後がカタカナなら別の語の一部（例：アカスリの中のカス）なので数えない
  const KATA = /[ァ-ヶー]/;
  const standalone = (text, w) => {
    if (!/^[ァ-ヶー]+$/.test(w)) return text.includes(w);
    let i = text.indexOf(w);
    while (i >= 0) {
      const a = text[i - 1] || '', b = text[i + w.length] || '';
      if (!KATA.test(a) && !KATA.test(b)) return true;
      i = text.indexOf(w, i + 1);
    }
    return false;
  };
  const strongInReview = STRONG.filter(w => standalone(String(reviewText || ''), w));
  const restated = strongInReview.filter(w => standalone(r, w));
  const specific = SPECIFIC.filter(w => r.includes(w));
  return { affirm: [...new Set(affirm)], restated, specific };
}



/**
 * 口コミを判定する。
 * @returns {{star:number, needsHuman:boolean, complaint:boolean, hits:string[]}}
 *   needsHuman … 自動送信しない（公式LINEで社長と従業員に確認）。★3以下は全件
 *   complaint  … 不満・悪口が書かれている（★1-2は本文に関係なく不満として扱う）
 */
export function classifyReview(text, star) {
  const t = String(text || '');
  const low = t.toLowerCase();
  const s = Number(star) || 0;
  const strong = [
    ...STRONG.filter(w => t.includes(w)),
    ...(STRONG_RE.some(re => re.test(t)) ? ['最低'] : []),
    ...STRONG_EN.filter(w => low.includes(w)),
  ];
  const broad = BROAD.filter(w => t.includes(w));
  return {
    star: s,
    needsHuman: s <= 3 || strong.length > 0,
    complaint: s <= 2 || strong.length > 0 || broad.length > 0,
    hits: [...new Set([...strong, ...broad])].slice(0, 8),
  };
}


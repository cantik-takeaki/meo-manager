/** 返信に、口コミに書かれていない店の情報や来店状況の決めつけが無いかを見る */
export function findUnsupported(reply, reviewText = '') {
  const r = String(reply || '');
  const v = String(reviewText || '');
  const storeInfo = STORE_INFO.filter(w => r.includes(w) && !v.includes(w));
  const visit = [];
  for (const g of VISIT) {
    const said = g.say.filter(w => r.includes(w));
    if (said.length && !g.need.some(w => v.includes(w))) visit.push(...said);
  }
  return { storeInfo, visit };
}


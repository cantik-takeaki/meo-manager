// 食事・利用体験を先に、再訪やおすすめは結びに置く。
const closings = new Set(['また来たい','おすすめしたい']);
function wording(keys,version) {
  const remaining=new Set(keys);
  const lines=[],ending=[];
  const opening=[];
  for(const key of ['予約が取りやすい','受付の流れが分かりやすかった']){
    if(remaining.delete(key))opening.push(singles[key][0]);
  }
  if(opening.length && remaining.has('説明が分かりやすかった') && remaining.has('質問する時間があった')){
    lines.push('説明の内容がよく分かりましたし、質問する時間もありました。');
    remaining.delete('説明が分かりやすかった');
    remaining.delete('質問する時間があった');
  }
  for(const [a,b,...phrases] of pairs){
    if(!remaining.has(a)||!remaining.has(b))continue;
    (closings.has(a)||closings.has(b)?ending:lines).push(phrases[version%phrases.length]);
    remaining.delete(a);remaining.delete(b);
  }
  for(const key of remaining){
    const phrases=singles[key];
    (closings.has(key)?ending:lines).push(phrases[version%phrases.length]);
  }
  return [...opening,...lines,...ending].join('');
}
export async function japaneseParagraph(selected,free,complete){
  const drafts=[...new Set([wording(selected,0),wording(selected,1)])];
  let index=0,source='template';
  try{
    const raw=await complete('実体験に基づく口コミの候補です。選択にない情報は加えず、最も自然に読める文章の番号をJSONのchoices配列で一つ返してください。'+JSON.stringify(drafts),{maxTokens:100,temperature:0,reviewChoices:true});
    const data=JSON.parse(raw);
    const pick=Array.isArray(data)?data:data?.choices;
    if(pick?.length===1 && Number.isInteger(pick[0]) && drafts[pick[0]]!==undefined){index=pick[0];source='ai';}
  }catch{/* 利用できないときも選択された事実のみを返す。 */}
  return {content:[drafts[index],free].filter(Boolean).join('\n'),source};
}

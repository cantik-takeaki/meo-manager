// 三回の作り直しで「お礼と体験→再訪」「再訪→お礼と体験」「感想→お礼→再訪」を選べる。
export function gratefulPassages(fact,passages){
  const thanks=thanksFor(fact);
  const returns=passages[1].map(form=>form.slice(0,form.indexOf('。')+1));
  const first=[],second=[],middle=[];
  for(let i=0;i<thanks.length;i++){
    for(let j=0;j<returns.length;j++){
      if(!thanks[i].slice(0,-1).includes('。'))first.push(thanks[i]+returns[j]);

    }
  }
  for(const paragraph of passages[0]){
    const split=paragraph.indexOf('。')+1;
    const expression=fact==='料理がおいしい'?'ごちそうさまでした。':'ありがとうございました。';
    middle.push(paragraph.slice(0,split)+expression+paragraph.slice(split));
  }
  if(fact==='料理がおいしい'){
    // 再訪への理由と食後のお礼をひと続きで伝える。前後の入れ替えにはしない。
    second.splice(0,second.length,
      'また食べに来たいと思える味でした。美味しい食事をごちそうさまでした。',
      '次もここで食事をしたいと思うほど美味しくいただきました。ごちそうさまです。',
      'また伺いたくなるような美味しいお料理をありがとうございました。',
      'もう一度食べたくなる味でした。美味しい食事をありがとうございます。',
      'また来たいと思ったのは料理が好みの味だったからです。どうもごちそうさまでした。',
      'この味ならまた食べに来たいです。お料理を美味しくいただきありがとうございました。',
      '次の機会にも食べたい味でした。どうもごちそうさまでした。',
      'またこちらで食べたいと思いました。美味しいお食事をありがとうございます。',
      'また食事に来たくなるお料理でした。どうもごちそうさまです。');
  }
  const revisitThanks={
    '施術が丁寧':[
      'またお願いしたいと思えるほど丁寧に施術してくださりありがとうございました。',
      '次もこちらで受けたいです。施術の丁寧さがありがたかったです。',
      'また受けに来たいです。施術を丁寧にしてくださりありがとうございます。',
      'もう一度お願いしたくなる丁寧な施術をありがとうございました。',
      'ここでまた施術を受けたいです。丁寧にしてくださりどうもありがとうございました。',
      'また伺いたくなりました。施術を丁寧にしていただけたのがありがたかったです。',
      '次もこちらにお願いしたいと思うほど丁寧な施術でした。どうもありがとうございました。',
      'またここに来ようと思います。丁寧に施術していただけてありがたいです。',
      'またお世話になりたいです。今回の丁寧な施術をありがとうございました。'],
    '指導が丁寧':['またこちらで教わりたいと思うほど丁寧に指導していただきありがとうございました。','次もお願いしたいです。丁寧に教えてもらえてありがたかったです。'],
    '説明が分かりやすかった':['次もこちらに伺いたいです。理解しやすい説明をありがとうございました。','また来たいと思える分かりやすいご説明をありがとうございました。']
  }[fact];
  if(revisitThanks)second.splice(0,second.length,...revisitThanks);
  return [first,second,middle];
}
